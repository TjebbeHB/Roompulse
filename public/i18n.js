const RULES = [
  [/^PERSPECTIVE (\d+)$/, 'PERSPECTIEF $1'],
  [/^(\d)\.(\d)$/, '$1,$2'],
  [/^(\d)\.(\d)$/, '$1,$2'],
  [/^(\d+) responses?$/, (m, n) => `${n} ${n === '1' ? 'reactie' : 'reacties'}`],
  [/^(\d) out of 5$/, '$1 van de 5'],
  [/^(Rating scale|Open response|Multiple choice) · (\d+) responses$/, (m, t, n) => `${NL[t]} · ${n} ${n === '1' ? 'reactie' : 'reacties'}`],
];

const stored = (() => { try { return localStorage.getItem('roompulse-lang'); } catch { return null; } })();
export const lang = stored || ((navigator.language || '').toLowerCase().startsWith('nl') ? 'nl' : 'en');
document.documentElement.lang = lang;

function tr(text) {
  const core = text.trim();
  if (!core) return null;
  let out = NL[core];
  if (out === undefined) for (const [re, rep] of RULES) if (re.test(core)) { out = core.replace(re, rep); break; }
  if (out === undefined || out === core) return null;
  return text.replace(core, out);
}
const ATTRS = ['placeholder', 'aria-label', 'alt', 'title'];
function translate(root) {
  if (root.nodeType === 3) { if (!root.parentElement?.closest('[data-user],script,style')) { const t = tr(root.nodeValue); if (t !== null) root.nodeValue = t; } return; }
  if (root.nodeType !== 1 || root.closest('[data-user],script,style')) return;
  for (const a of ATTRS) if (root.hasAttribute(a)) { const t = tr(root.getAttribute(a)); if (t !== null) root.setAttribute(a, t); }
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT, { acceptNode: n => (n.nodeType === 1 ? n : n.parentElement).closest('[data-user],script,style') ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT });
  let n; while ((n = walker.nextNode())) {
    if (n.nodeType === 3) { const t = tr(n.nodeValue); if (t !== null) n.nodeValue = t; }
    else for (const a of ATTRS) if (n.hasAttribute(a)) { const t = tr(n.getAttribute(a)); if (t !== null) n.setAttribute(a, t); }
  }
}

export function startI18n() {
  const toggle = document.getElementById('lang-toggle');
  if (toggle) {
    toggle.querySelectorAll('[data-l]').forEach(el => el.classList.toggle('on', el.dataset.l === lang));
    toggle.setAttribute('aria-label', lang === 'nl' ? 'Switch to English' : 'Schakel naar Nederlands');
    toggle.onclick = () => { try { localStorage.setItem('roompulse-lang', lang === 'nl' ? 'en' : 'nl'); } catch {} location.reload(); };
  }
  if (lang !== 'nl') return;
  const t = tr(document.title); if (t !== null) document.title = t;
  translate(document.body);
  new MutationObserver(list => {
    for (const m of list) {
      if (m.type === 'characterData') translate(m.target);
      else if (m.type === 'attributes') translate(m.target);
      else m.addedNodes.forEach(translate);
    }
  }).observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRS });
}
